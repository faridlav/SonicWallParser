using SonicWallParser.Analysis;
using SonicWallParser.Export;
using SonicWallParser.Findings;
using SonicWallParser.Migration;
using SonicWallParser.Models;

namespace SonicWallParser.Reporting;

/// <summary>Which optional pages to produce, and how the checks are tuned.</summary>
public sealed class ReportOptions
{
    /// <summary>Produce the security findings page.</summary>
    public bool IncludeFindings { get; set; } = true;

    /// <summary>Produce the migration checklist page.</summary>
    public bool IncludeMigration { get; set; } = true;

    /// <summary>Check selection and thresholds.</summary>
    public FindingOptions Findings { get; set; } = new();
}

/// <summary>
/// Everything computed once for one configuration: the analysis, the findings, the migration checklist and the
/// documents built from them. The CLI, the HTML file and the separate Markdown and PDF files all use this, so
/// they cannot disagree.
/// </summary>
public sealed class ReportSet
{
    private ReportSet(SonicWallConfig config, AnalysisResult analysis, FindingsResult findings,
        ReportDocument findingsDocument, ReportDocument migrationDocument, MigrationStats migrationStats, ReportOptions options)
    {
        Config = config;
        Analysis = analysis;
        Findings = findings;
        FindingsDocument = findingsDocument;
        MigrationDocument = migrationDocument;
        MigrationStats = migrationStats;
        Options = options;
    }

    public SonicWallConfig Config { get; }
    public AnalysisResult Analysis { get; }
    public FindingsResult Findings { get; }
    public ReportDocument FindingsDocument { get; }
    public ReportDocument MigrationDocument { get; }
    public MigrationStats MigrationStats { get; }
    public ReportOptions Options { get; }

    /// <summary>Computes the analysis, findings and checklist for a configuration.</summary>
    public static ReportSet Create(SonicWallConfig config, ReportOptions? options = null)
    {
        options ??= new ReportOptions();
        var analysis = ConfigAnalyzer.Analyze(config);
        var findings = FindingsEngine.Run(config, analysis, options.Findings);
        var findingsDoc = FindingsReport.Build(config, analysis, findings);
        var (migrationDoc, stats) = MigrationReport.Build(config, analysis, findings);
        return new ReportSet(config, analysis, findings, findingsDoc, migrationDoc, stats, options);
    }

    /// <summary>The main configuration report with the executive summary first.</summary>
    public ReportDocument Main(ReportTarget target)
    {
        var doc = ReportBuilder.Build(Config, Analysis, target);
        doc.Sections.Insert(0, ExecutiveSummary());
        return doc;
    }

    /// <summary>
    /// The single HTML document: the main report plus the findings page after the device section and the
    /// migration checklist at the end, so locations on the findings page link to the exact item above.
    /// </summary>
    public ReportDocument Html()
    {
        var doc = Main(ReportTarget.Html);

        if (Options.IncludeFindings)
        {
            var at = Math.Min(2, doc.Sections.Count);
            doc.Sections.InsertRange(at, FindingsDocument.Sections.Select(s => Prefixed(s, "Findings: ")));
        }

        if (Options.IncludeMigration)
            doc.Sections.AddRange(MigrationDocument.Sections.Select(s => Prefixed(s, "Migration: ", collapsed: true)));

        return doc;
    }

    private static ReportSection Prefixed(ReportSection source, string prefix, bool collapsed = false)
    {
        var copy = new ReportSection
        {
            Id = source.Id,
            Title = prefix + source.Title,
            Count = source.Count,
            Collapsed = collapsed || source.Collapsed,
        };
        copy.Blocks.AddRange(source.Blocks);
        return copy;
    }

    private ReportSection ExecutiveSummary()
    {
        var g = Config.Global;
        var s = new ReportSection { Id = "sec-summary", Title = "Executive Summary" };
        var o = Analysis.RuleOrigins;

        s.Pairs(
            ("Device", $"{g.ProductName} (serial {ReportBuilder.None(g.SerialNumber)})"),
            ("Firmware", $"{g.BuildNumber}, {g.Firmware.Description}"),
            ("Zones and interfaces", $"{Config.Zones.Count} zones, {Config.Interfaces.Count} interfaces"),
            ("Firewall rules (IPv4)", $"{Config.FirewallPolicies.Count} total: {o[RuleOrigin.Custom]} custom, {o[RuleOrigin.AutoGenerated]} auto-generated, {o[RuleOrigin.BuiltInDefault]} built-in default"),
            ("Unused custom rules", $"{Analysis.UnusedRules.Count} (zero hits, for review only)"),
            ("NAT policies", $"{Config.NatPolicies.Count} IPv4, {Config.NatPoliciesV6.Count} IPv6"),
            ("VPN policies", Config.VpnPolicies.Count.ToString()),
            ("Local users", Config.Users.Count.ToString()),
            ("Objects", $"{Config.AddressObjects.Count + Config.AddressObjectsV6.Count + Config.MacAddressObjects.Count} address, {Config.ServiceObjects.Count} service, {Config.Schedules.Count} schedule"));

        if (Options.IncludeFindings)
        {
            s.Pairs(
                ("Findings", string.Join(", ", Enum.GetValues<Severity>().Select(sev => $"{Findings.Count(sev)} {sev.ToString().ToLowerInvariant()}"))),
                ("Checks not assessable from an export", Findings.NotAssessed.Count.ToString()));

            var top = Findings.Findings.Where(f => f.Severity <= Severity.High).Take(8).ToList();
            if (top.Count > 0)
            {
                s.Heading("Top findings");
                s.Table(["Severity", "Finding", "Where"],
                    top.Select(f => ReportBuilder.Row(null, FindingsReport.SeverityCell(f.Severity), new Cell(f.Title, CellStyle.Strong),
                        new Cell(f.Location, CellStyle.Normal, f.LinkTo))));
            }
            else
            {
                s.Note("No critical or high findings.");
            }
        }

        var warnings = ReportText.Warnings(Config);
        s.Note($"Coverage: {warnings.Count} parser warning(s), {Config.UnknownSections.Sum(u => u.KeyCount):N0} setting key(s) not read by this parser yet. " +
               "Values marked unverified have not been confirmed against the SonicOS UI.");
        return s;
    }
}
