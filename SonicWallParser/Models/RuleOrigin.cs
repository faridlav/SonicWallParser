namespace SonicWallParser.Models;

/// <summary>
/// Where a firewall rule came from. Derived from several fields because the
/// <c>policyDefaultRule</c> flag alone is a three-state value that cannot tell these apart.
/// </summary>
public enum RuleOrigin
{
    /// <summary>Created by the user (or an admin script). The only origin that feeds cleanup checks.</summary>
    Custom,

    /// <summary>Added automatically by SonicOS, for example for a VPN or a service object.</summary>
    AutoGenerated,

    /// <summary>The built-in zone-to-zone default rule.</summary>
    BuiltInDefault
}
