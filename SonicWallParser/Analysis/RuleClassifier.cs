using SonicWallParser.Models;

namespace SonicWallParser.Analysis;

/// <summary>
/// Derives the <see cref="RuleOrigin"/> of a firewall rule from several fields.
/// </summary>
/// <remarks>
/// Rules come from the measured sample findings (section 3). The IPv6 comment prefix
/// "IPv6:From Any to Any" is an UNVERIFIED assumption mirroring the IPv4 one.
/// </remarks>
public static class RuleClassifier
{
    private static readonly string[] AutoCommentPrefixes = ["Auto added", "Auto-added", "Auto generated"];
    private static readonly string[] DefaultCommentPrefixes = ["IPv4:From Any to Any", "IPv6:From Any to Any"];

    /// <summary>Name given to the built-in zone-to-zone rule on SonicOS 7.x.</summary>
    public const string BuiltInRuleName = "Default Access Rule";

    /// <summary>Value of <c>policyDefaultRule</c> that marks a built-in default on 7.x.</summary>
    public const int BuiltInDefaultFlag = 2;

    /// <summary>Classifies one rule. An empty value or "Any" means any.</summary>
    public static RuleOrigin Classify(
        string name,
        string comment,
        string sourceNet,
        string destNet,
        string destService,
        int defaultRuleFlag)
    {
        var trimmedComment = comment.Trim();

        if (StartsWithAny(trimmedComment, AutoCommentPrefixes))
            return RuleOrigin.AutoGenerated;

        var anySourceAndDest = IsAny(sourceNet) && IsAny(destNet);

        // The generated "IPv4:From Any to Any ..." comment is enough on its own, even when the rule names
        // a service. Measured: on 7.1.2 a WLAN to MULTICAST rule carries that comment and a specific
        // service, and the sample findings only reach their count of 13 custom rules if it is not custom.
        if (anySourceAndDest && StartsWithAny(trimmedComment, DefaultCommentPrefixes))
            return RuleOrigin.BuiltInDefault;

        // The 7.x built-in rule is identified by its name and flag, and must be any/any/any.
        if (anySourceAndDest && IsAny(destService) &&
            string.Equals(name.Trim(), BuiltInRuleName, StringComparison.OrdinalIgnoreCase) &&
            defaultRuleFlag == BuiltInDefaultFlag)
            return RuleOrigin.BuiltInDefault;

        return RuleOrigin.Custom;
    }

    private static bool IsAny(string value)
        => string.IsNullOrWhiteSpace(value) || value.Trim().Equals("Any", StringComparison.OrdinalIgnoreCase);

    private static bool StartsWithAny(string text, string[] prefixes)
        => prefixes.Any(p => text.StartsWith(p, StringComparison.OrdinalIgnoreCase));
}
