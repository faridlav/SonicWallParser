using SonicWallParser.Analysis;
using SonicWallParser.Models;

namespace SonicWallParser.Export;

/// <summary>
/// Text helpers shared by all exporters, so the same value is always worded the same way.
/// </summary>
public static class ReportText
{
    /// <summary>Wording for a value whose meaning has not been confirmed.</summary>
    public const string UnverifiedNote = "unverified";

    /// <summary>Formats a DHCP lease value. The unit is not confirmed, so it is stated as unverified.</summary>
    public static string Lease(int rawLease)
        => rawLease <= 0 ? "Not set" : $"{rawLease} (minutes, {UnverifiedNote})";

    /// <summary>Yes, No or Unknown for a flag whose source may not exist on a firmware generation.</summary>
    public static string YesNoUnknown(bool? value)
        => value is null ? "Unknown" : value.Value ? "Yes" : "No";

    /// <summary>Formats a timestamp in UTC so the same file gives the same report on any machine.</summary>
    public static string Utc(DateTime value)
        => value == DateTime.MinValue ? "Never" : value.ToUniversalTime().ToString("yyyy-MM-dd HH:mm:ss") + " UTC";

    /// <summary>Warnings and errors from parsing and extraction. Informational notes are excluded.</summary>
    public static List<ParseDiagnostic> Warnings(SonicWallConfig config)
        => config.Diagnostics.Where(d => d.Severity != ParseSeverity.Info).ToList();

    /// <summary>One line stating how many IPv4 rules are custom, auto-generated and built-in defaults.</summary>
    public static string RuleOriginSummary(SonicWallConfig config)
    {
        var counts = RuleAudit.CountByOrigin(config.FirewallPolicies);
        return $"Rule origin: {counts[RuleOrigin.Custom]} custom, {counts[RuleOrigin.AutoGenerated]} auto-generated, " +
               $"{counts[RuleOrigin.BuiltInDefault]} built-in default. " +
               $"{RuleAudit.UnusedRules(config.FirewallPolicies).Count} custom rule(s) are unused (zero hits).";
    }

    /// <summary>The unverified-action footnote, or null when every action value in use is confirmed.</summary>
    public static string? ActionNote(SonicWallConfig config)
        => config.FirewallPolicies.Any(p => PolicyActions.IsUnverified(p.Action)) ||
           config.FirewallPoliciesV6.Any(p => PolicyActions.IsUnverified(p.Action))
            ? PolicyActions.UnverifiedNote
            : null;

    /// <summary>Escapes a value for use inside a Markdown table cell.</summary>
    public static string MdCell(string? value)
    {
        if (string.IsNullOrEmpty(value))
            return string.Empty;

        return value
            .Replace("\\", "\\\\")
            .Replace("|", "\\|")
            .Replace("\r\n", " ")
            .Replace('\n', ' ')
            .Replace('\r', ' ');
    }
}
