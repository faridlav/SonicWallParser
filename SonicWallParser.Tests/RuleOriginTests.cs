using SonicWallParser.Analysis;
using SonicWallParser.Export;
using SonicWallParser.Models;
using SonicWallParser.Parsing;
using Xunit;

namespace SonicWallParser.Tests;

public class RuleOriginTests
{
    // ---- classification (rules from the sample findings, section 3) -------------------------

    [Theory]
    [InlineData("Auto added rule for X")]
    [InlineData("Auto-added by SonicOS")]
    [InlineData("Auto generated for VPN")]
    [InlineData("  auto added (lower case, padded)")]
    public void Classify_AutoGenerated_ByCommentPrefix(string comment)
        => Assert.Equal(RuleOrigin.AutoGenerated,
            RuleClassifier.Classify("", comment, "Corp LAN", "Web Server", "HTTPS", 1));

    [Fact]
    public void Classify_AutoGenerated_WinsOverAnyToAny()
        => Assert.Equal(RuleOrigin.AutoGenerated,
            RuleClassifier.Classify("Default Access Rule", "Auto added for DHCP", "", "", "", 2));

    [Fact]
    public void Classify_BuiltInDefault_ByIpv4AnyToAnyComment()
        => Assert.Equal(RuleOrigin.BuiltInDefault,
            RuleClassifier.Classify("", "IPv4:From Any to Any for LAN", "", "", "", 1));

    [Fact]
    public void Classify_BuiltInDefault_ByIpv4AnyToAnyComment_EvenWhenAServiceIsNamed()
        => Assert.Equal(RuleOrigin.BuiltInDefault,
            RuleClassifier.Classify("Custom Access Rule", "IPv4:From Any to Any f", "", "", "mDNS", 1));

    [Fact]
    public void Classify_BuiltInDefault_ByNameAndFlagTwo()
        => Assert.Equal(RuleOrigin.BuiltInDefault,
            RuleClassifier.Classify("Default Access Rule", "", "", "", "", 2));

    [Fact]
    public void Classify_DefaultAccessRuleName_WithFlagOne_IsCustom()
        => Assert.Equal(RuleOrigin.Custom,
            RuleClassifier.Classify("Default Access Rule", "", "", "", "", 1));

    [Fact]
    public void Classify_DefaultAccessRuleName_WithSpecificService_IsCustom()
        => Assert.Equal(RuleOrigin.Custom,
            RuleClassifier.Classify("Default Access Rule", "", "", "", "HTTPS", 2));

    [Theory]
    [InlineData("", "", "Corp LAN", "Web Server", "HTTPS")]
    [InlineData("Custom Access Rule", "Permit web", "", "Web Server", "HTTPS")]
    [InlineData("Allow VPN users", "", "Corp LAN", "", "")]
    public void Classify_Custom_Otherwise(string name, string comment, string src, string dst, string svc)
        => Assert.Equal(RuleOrigin.Custom, RuleClassifier.Classify(name, comment, src, dst, svc, 1));

    [Fact]
    public void Classify_TreatsTheWordAnyAsAny()
        => Assert.Equal(RuleOrigin.BuiltInDefault,
            RuleClassifier.Classify("Default Access Rule", "", "Any", "any", "ANY", 2));

    // ---- extraction and the shared audit ------------------------------------------------------

    private static SyntheticExp MixedRules()
        => SyntheticExp.MinimalV7()
            // index 0 is already a never-hit custom rule from MinimalV7
            .Rule(1, "LAN", "WAN", srcNet: "Corp LAN", dstNet: "Web Server", dstSvc: "HTTPS",
                name: "Custom Access Rule", hits: 25, lastHit: 1700000000)
            .Rule(2, "WAN", "LAN", comment: "Auto added rule for VPN", hits: 0)
            .Rule(3, "WAN", "LAN", name: "Default Access Rule", defaultRule: 2, action: 0, hits: 0)
            .Rule(4, "LAN", "DMZ", comment: "IPv4:From Any to Any for LAN", hits: 0)
            .Rule(5, "LAN", "WAN", srcNet: "Corp LAN", dstNet: "Web Server", dstSvc: "SSH",
                name: "Disabled custom", hits: 0, enabled: false)
            .Rule(6, "LAN", "WAN", srcNet: "Corp LAN", dstNet: "Web Server", dstSvc: "RDP",
                name: "Hit then reset", hits: 0, lastHit: 1700000000);

    [Fact]
    public void Extract_DerivesOriginForEveryRule()
    {
        var rules = TableExtractor.Extract(MixedRules().Values).FirewallPolicies;

        Assert.Equal(RuleOrigin.Custom, rules[0].Origin);
        Assert.Equal(RuleOrigin.Custom, rules[1].Origin);
        Assert.Equal(RuleOrigin.AutoGenerated, rules[2].Origin);
        Assert.Equal(RuleOrigin.BuiltInDefault, rules[3].Origin);
        Assert.Equal(RuleOrigin.BuiltInDefault, rules[4].Origin);
        Assert.Equal(2, rules[3].DefaultRuleFlag);
    }

    [Fact]
    public void Audit_OnlyCountsEnabledNeverHitCustomRules()
    {
        var rules = TableExtractor.Extract(MixedRules().Values).FirewallPolicies;

        var unused = RuleAudit.UnusedRules(rules);

        // Only rule 0: custom, enabled, zero hits, never hit. Rule 1 has hits, 5 is disabled,
        // 6 has a last-hit time (counters were reset), 2 to 4 are not custom.
        Assert.Equal([0], unused.Select(r => r.Index));
    }

    [Fact]
    public void Audit_NeverListsBuiltInOrAutoGeneratedRules_EvenWithZeroHits()
    {
        var exp = SyntheticExp.V7().Zone(0, "LAN")
            .Rule(0, "WAN", "LAN", name: "Default Access Rule", defaultRule: 2)
            .Rule(1, "WAN", "LAN", comment: "Auto added rule");

        var rules = TableExtractor.Extract(exp.Values).FirewallPolicies;

        Assert.Empty(RuleAudit.UnusedRules(rules));
    }

    [Fact]
    public void Audit_CountByOrigin_SumsToTheRuleCount()
    {
        var rules = TableExtractor.Extract(MixedRules().Values).FirewallPolicies;

        var counts = RuleAudit.CountByOrigin(rules);

        Assert.Equal(rules.Count, counts.Values.Sum());
        Assert.Equal(4, counts[RuleOrigin.Custom]);
        Assert.Equal(1, counts[RuleOrigin.AutoGenerated]);
        Assert.Equal(2, counts[RuleOrigin.BuiltInDefault]);
    }

    [Fact]
    public void UnusedCount_IsIdenticalInEveryOutput()
    {
        var config = TableExtractor.Extract(MixedRules().Values);
        var expected = RuleAudit.UnusedRules(config.FirewallPolicies).Count;
        Assert.Equal(1, expected);

        var md = MarkdownExporter.Generate(config);
        var htmlPath = Path.Combine(Path.GetTempPath(), $"{Guid.NewGuid():N}.html");
        HtmlExporter.Generate(config, htmlPath);
        var html = File.ReadAllText(htmlPath);

        // The origin summary line, rendered in every format, carries the shared count.
        var line = ReportText.RuleOriginSummary(config);
        Assert.Contains($"{expected} custom rule(s) are unused", line);
        Assert.Contains(line, md);
        Assert.Contains(System.Net.WebUtility.HtmlEncode(line), html);

        // The audit section lists exactly that many rows in Markdown.
        var section = md[md.IndexOf("## ⚠ Unused Custom Rules", StringComparison.Ordinal)..];
        var rows = section.Split('\n').Count(l => l.StartsWith("| ") && !l.StartsWith("| #"));
        Assert.Equal(expected, rows);

        // The caveat is present wherever the section is.
        Assert.Contains("Hit counters reset", md);
        Assert.Contains("Hit counters reset", html);
    }

    [Fact]
    public void Reports_OmitTheUnusedSection_WhenThereAreNoCustomRules()
    {
        var exp = SyntheticExp.V7().Zone(0, "LAN")
            .Rule(0, "WAN", "LAN", name: "Default Access Rule", defaultRule: 2);

        var md = MarkdownExporter.Generate(TableExtractor.Extract(exp.Values));

        Assert.DoesNotContain("Unused Custom Rules", md);
    }

    // ---- action labels (unverified) -----------------------------------------------------------

    [Theory]
    [InlineData(2, "Allow")]
    [InlineData(0, "Deny (0)")]
    [InlineData(1, "Unknown(1)")]
    [InlineData(9, "Unknown(9)")]
    public void ActionLabel_FollowsTheConfirmedAndUnverifiedMapping(int action, string label)
        => Assert.Equal(label, PolicyActions.Label(action));

    [Theory]
    [InlineData(2, "Allow")]
    [InlineData(0, "Deny (0)")]
    [InlineData(1, "Unknown(1)")]
    public void RuleModels_UseTheSharedActionLabel(int action, string label)
    {
        Assert.Equal(label, new FirewallPolicy { Action = action }.ActionLabel);
        Assert.Equal(label, new FirewallPolicyV6 { Action = action }.ActionLabel);
    }

    [Fact]
    public void RenderedRuleTables_NeverShowTheOldDiscardOrGuessedDenyLabels()
    {
        var exp = SyntheticExp.MinimalV7().Rule(1, "WAN", "LAN", name: "Default Access Rule", defaultRule: 2, action: 0)
            .Rule(2, "LAN", "WAN", name: "Odd", action: 1);

        var md = MarkdownExporter.Generate(TableExtractor.Extract(exp.Values));

        Assert.DoesNotContain("Discard", md);
        Assert.Contains("| Deny (0) |", md);
        Assert.Contains("| Unknown(1) |", md);
        Assert.DoesNotContain("| Deny |", md);
    }

    [Fact]
    public void Reports_FlagTheUnverifiedActionValue()
    {
        var config = TableExtractor.Extract(MixedRules().Values);

        Assert.Contains("unverified", MarkdownExporter.Generate(config));
        Assert.NotNull(ReportText.ActionNote(config));
    }

    [Fact]
    public void Reports_DoNotFlagActions_WhenOnlyAllowIsUsed()
    {
        var config = TableExtractor.Extract(SyntheticExp.MinimalV7().Values);

        Assert.Null(ReportText.ActionNote(config));
    }

    // ---- NAT hit counter removal ----------------------------------------------------------------

    [Fact]
    public void NatHtml_HasNoHitsColumn()
    {
        var exp = SyntheticExp.MinimalV7()
            .Set("natPolicyOrigSrc_0", "").Set("natPolicyEnabled_0", "1").Set("natPolicyComment_0", "synthetic");
        var config = TableExtractor.Extract(exp.Values);
        var path = Path.Combine(Path.GetTempPath(), $"{Guid.NewGuid():N}.html");

        HtmlExporter.Generate(config, path);

        var html = File.ReadAllText(path);
        var natStart = html.IndexOf("NAT Policies (IPv4)", StringComparison.Ordinal);
        var natTable = html[natStart..html.IndexOf("</table>", natStart, StringComparison.Ordinal)];
        Assert.DoesNotContain("<th>Hits</th>", natTable);
    }
}
